export function initPaper(root) {
  const st = { ds: "ETTh1", hz: null, metric: 0 };
  const hzBox = h("div");
  const barsBox = h("div");
  const verdict = h("div", { class: "callout" });

  function horizons() {
    return Object.keys(TABLE2[st.ds]).map(Number);
  }
  function renderHorizons() {
    const hs = horizons();
    if (!hs.includes(st.hz)) st.hz = hs[0];
    hzBox.replaceChildren(ctl(T.horizon, segToggle(hs.map((v) => ({ value: v, label: String(v) })), st.hz, (v) => ((st.hz = v), render()))));
  }
  function render() {
    const row = TABLE2[st.ds][st.hz];
    const imp = row[0];
    const val = (m) => row[1 + METHODS.indexOf(m) * 2 + st.metric];
    const max = Math.max(...METHODS.map(val));
    const best = METHODS.reduce((a, b) => (val(b) < val(a) ? b : a));
    const grid = h("div", { class: "bars", role: "table", "aria-label": T.table2Label });
    METHODS.forEach((m, i) => {
      if (i === 3 || i === 8) grid.append(h("div", { class: "sep" }));
      const v = val(m);
      const kind = LINEAR.has(m) ? T.ltsfLinear : m === "Repeat" ? T.naive : T.transformer;
      const rowEls = [
        h("div", { class: "name" }, m, h("small", null, kind)),
        h("div", { class: "track" }, h("div", { class: `fill${LINEAR.has(m) ? " lin" : ""}`, style: { width: `${(100 * v) / max}%` } })),
        h("div", { class: "num" }, v.toFixed(3)),
      ];
      for (const el of rowEls) {
        if (m === best) el.classList.add("best");
        el.addEventListener("pointermove", (ev) => showTip(`<b>${m}</b> · ${st.ds}, T = ${st.hz}<br>MSE <span class="mono">${val0(m, 0).toFixed(3)}</span> · MAE <span class="mono">${val0(m, 1).toFixed(3)}</span>`, ev));
        el.addEventListener("pointerleave", hideTip);
      }
      grid.append(...rowEls);
    });
    barsBox.replaceChildren(grid);
    const bestLin = ["Linear", "NLinear", "DLinear"].reduce((a, b) => (val0(b, 0) < val0(a, 0) ? b : a));
    const bestTr = TRANSFORMERS.reduce((a, b) => (val0(b, 0) < val0(a, 0) ? b : a));
    const repeatBeats = val0("Repeat", 0) < val0(bestTr, 0);
    verdict.replaceChildren(...[T.paperVerdict(st.ds, st.hz, bestLin, val0(bestLin, 0), bestTr, val0(bestTr, 0), imp), ...(repeatBeats ? [" ", T.repeatBeats] : [])]);
    function val0(m, k) {
      return row[1 + METHODS.indexOf(m) * 2 + k];
    }
  }
  root.replaceChildren(
    h("div", { class: "controls" },
      ctl(T.dataset, segToggle(Object.keys(TABLE2).map((d) => ({ value: d, label: d })), st.ds, (v) => {
        st.ds = v;
        renderHorizons();
        render();
      }))),
    h("div", { class: "controls" }, hzBox,
      ctl(T.metric, segToggle([{ value: 0, label: "MSE" }, { value: 1, label: "MAE" }], 0, (v) => ((st.metric = v), render())))),
    barsBox, verdict);
  renderHorizons();
  render();
  return { redraw: render };
}

